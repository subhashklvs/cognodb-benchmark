"""
Turn results/*.json into a markdown results matrix you can paste straight
into the README, plus a raw combined JSON for the charting script.

Usage:
    python harness/build_report.py
    -> writes results/report.md and results/combined.json
"""
import json
import sys

import os
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))
from harness.config import PLATFORMS, RESULTS_DIR
from harness.stats import load_all_results
from tabulate import tabulate


def fmt(v):
    return "n/a" if v is None else v


def build_load_table(all_results):
    rows = []
    for p in PLATFORMS:
        r = all_results.get(p.key, {}).get("load")
        if not r:
            rows.append([p.display_name, "n/a", "n/a", "n/a", "n/a"])
            continue
        rows.append([p.display_name, r["node_count"], r["edge_count"],
                     fmt(r["nodes_per_second"]), fmt(r["relationships_per_second"])])
    return tabulate(rows, headers=["Platform", "Nodes", "Relationships",
                                    "Nodes/sec", "Rels/sec"], tablefmt="github")


def build_traversal_table(all_results):
    rows = []
    for p in PLATFORMS:
        r = all_results.get(p.key, {}).get("traversals")
        if not r:
            rows.append([p.display_name] + ["n/a"] * 6)
            continue
        row = [p.display_name]
        for hop in ("1", "2", "3"):
            h = r["hops"].get(hop, {})
            row += [fmt(h.get("p50")), fmt(h.get("p95"))]
        rows.append(row)
    return tabulate(rows, headers=["Platform", "1-hop p50", "1-hop p95",
                                    "2-hop p50", "2-hop p95", "3-hop p50", "3-hop p95"],
                     tablefmt="github")


def build_lookup_table(all_results):
    rows = []
    for p in PLATFORMS:
        r = all_results.get(p.key, {}).get("lookups")
        if not r:
            rows.append([p.display_name] + ["n/a"] * 4)
            continue
        pl, fl = r["point_lookup"], r["filtered_lookup"]
        rows.append([p.display_name, fmt(pl.get("p50")), fmt(pl.get("p95")),
                     fmt(fl.get("p50")), fmt(fl.get("p95"))])
    return tabulate(rows, headers=["Platform", "Point p50", "Point p95",
                                    "Filtered p50", "Filtered p95"], tablefmt="github")


def build_aggregation_table(all_results):
    rows = []
    for p in PLATFORMS:
        r = all_results.get(p.key, {}).get("aggregations")
        if not r:
            rows.append([p.display_name] + ["n/a"] * 4)
            continue
        c, g = r["count_aggregation"], r["groupby_aggregation"]
        rows.append([p.display_name, fmt(c.get("p50")), fmt(c.get("p95")),
                     fmt(g.get("p50")), fmt(g.get("p95"))])
    return tabulate(rows, headers=["Platform", "Count p50", "Count p95",
                                    "GroupBy p50", "GroupBy p95"], tablefmt="github")


def build_mixed_table(all_results):
    rows = []
    for p in PLATFORMS:
        r = all_results.get(p.key, {}).get("mixed_workload")
        if not r:
            continue
        for level in r["sweep"]:
            rows.append([p.display_name, level["concurrency"], level.get("write_ratio"),
                         fmt(level.get("throughput_qps")), fmt(level.get("p50")), fmt(level.get("p95")),
                         level.get("errors", 0)])
    return tabulate(rows, headers=["Platform", "Concurrency", "Write ratio",
                                    "QPS", "p50 (ms)", "p95 (ms)", "Errors"], tablefmt="github")


def build_resource_table():
    rows = [[p.display_name, p.vcpu, p.ram_mb, p.disk_gb, p.notes] for p in PLATFORMS]
    return tabulate(rows, headers=["Platform", "vCPU", "RAM (MB)", "Disk (GB)", "Notes"], tablefmt="github")


if __name__ == "__main__":
    all_results = load_all_results(RESULTS_DIR)

    md = ["# Benchmark results\n", "_Auto-generated by harness/build_report.py -- paste into README.md_\n"]
    md.append("## Resource parity\n\n" + build_resource_table() + "\n")
    md.append("## Data loading\n\n" + build_load_table(all_results) + "\n")
    md.append("## Traversals (ms)\n\n" + build_traversal_table(all_results) + "\n")
    md.append("## Lookups (ms)\n\n" + build_lookup_table(all_results) + "\n")
    md.append("## Aggregations (ms)\n\n" + build_aggregation_table(all_results) + "\n")
    md.append("## Mixed read/write workload\n\n" + build_mixed_table(all_results) + "\n")

    with open(f"{RESULTS_DIR}/report.md", "w") as f:
        f.write("\n".join(md))
    with open(f"{RESULTS_DIR}/combined.json", "w") as f:
        json.dump(all_results, f, indent=2)

    print(f"Wrote {RESULTS_DIR}/report.md and {RESULTS_DIR}/combined.json")
